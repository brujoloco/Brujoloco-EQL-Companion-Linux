// eslint.config.js — this project's own gate. It shares NOTHING with the desktop's.
//
// The desktop's `eslint.config.mjs` is type-aware over `tsconfig.node.json` /
// `tsconfig.web.json`, neither of which has ever included `mobile/`, and it carries a generated
// per-file ratchet of the desktop tree's debt. Pointing it at a React Native project would mean
// teaching it a third tsconfig, a JSX runtime it does not use and a ratchet it has no entries for.
// So `mobile/**` is in the desktop's ignore list and this file is the whole of the mobile gate.
//
// WHAT IT ENFORCES, and the two of them are the brief's:
//
//   `eslint-config-expo/flat` + typescript-eslint's TYPE-AWARE strict set — so `no-floating-
//   promises`, `no-misused-promises` and `no-unnecessary-condition` are live, which is most of
//   what goes wrong in an app whose whole job is a socket and a keystore;
//
//   and `no-explicit-any` as an ERROR with no escape, plus a 250-line ceiling per file, because
//   a component that has grown past 250 lines has stopped being a component.

const expo = require('eslint-config-expo/flat')
const tseslint = require('typescript-eslint')

module.exports = tseslint.config(
  {
    ignores: [
      'node_modules/**',
      '.expo/**',
      'dist/**',
      'android/**',
      'ios/**',
      // Generated by the two scripts, committed as data, never hand-edited.
      'src/phone/vectors.json',
      'src/phone/present/fixtures.json',
      // Run from the REPO ROOT through the desktop's tsx, against the desktop's tsconfig; they are
      // not part of this project's program and linting them here would need a third parser config.
      'scripts/**'
    ]
  },
  {
    // The two CommonJS config files at the project root. They are not in any tsconfig and they
    // are not modules; without this they fail `no-undef` on `__dirname` and `module`.
    files: ['*.js'],
    languageOptions: {
      sourceType: 'commonjs',
      globals: { __dirname: 'readonly', module: 'writable', require: 'readonly', process: 'readonly' }
    }
  },
  ...expo,
  {
    // TYPE-AWARE LINTING IS SCOPED TO THE APP'S OWN SOURCE. Spreading the typed configs at the
    // top level applies them to this file and to metro.config.js too, and a type-aware rule on a
    // CommonJS config file that is not in any tsconfig is an immediate crash rather than a miss.
    files: ['**/*.ts', '**/*.tsx'],
    extends: [tseslint.configs.strictTypeChecked, tseslint.configs.stylisticTypeChecked],
    languageOptions: {
      parserOptions: { projectService: true, tsconfigRootDir: __dirname }
    },
    linterOptions: { reportUnusedDisableDirectives: 'error' },
    rules: {
      '@typescript-eslint/no-explicit-any': 'error',
      // A type assertion is how a payload off a socket becomes a shape, and every one of them in
      // this app is beside the check that earned it. The rule fires on the checks themselves.
      '@typescript-eslint/consistent-type-assertions': 'off',
      '@typescript-eslint/restrict-template-expressions': ['error', { allowNumber: true }],
      'max-lines': ['error', { max: 250, skipBlankLines: true, skipComments: true }],
      'max-depth': ['error', 3],
      'max-params': ['error', 4],
      complexity: ['error', 12],
      // The app must not grow a second host or a second console. Both would be silent.
      'no-console': 'error',
      'no-restricted-globals': [
        'error',
        { name: 'fetch', message: 'This app speaks to share.eqzera.com over one WebSocket. Add a host to docs/plans/phone-native.md before adding a request.' }
      ]
    }
  },
  {
    // The suites drive fakes and read fixtures; a non-null assertion on a fixture row is clearer
    // than a guard that can never fire, and a long table of cases is the point of the file.
    files: ['**/*.test.ts', '**/*.test.tsx'],
    rules: {
      '@typescript-eslint/no-non-null-assertion': 'off',
      '@typescript-eslint/no-unsafe-assignment': 'off',
      'max-lines': 'off'
    }
  }
)
